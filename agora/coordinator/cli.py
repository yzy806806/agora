def build_parser() -> argparse.ArgumentParser:
    """Build the argument parser for the agora CLI."""
    from agora import __version__

    parser = argparse.ArgumentParser(
        prog="agora",
        description="Agora — Multi-Agent Deliberation Platform",
    )
    parser.add_argument(
        "--version", action="version",
        version=f"agora {__version__}",
    )

    sub = parser.add_subparsers(dest="command")

    # init
    sp_init = sub.add_parser("init", help="Interactive setup wizard")
    sp_init.add_argument("--enable-matrix", action="store_true",
                         help="Enable Matrix wakeup configuration")
    sp_init.set_defaults(func=_cmd_init)

    # serve
    sp_serve = sub.add_parser("serve", help="Start the coordinator server")
    sp_serve.add_argument("--host", default=None, help="Bind host")
    sp_serve.add_argument("--port", type=int, default=None, help="Bind port")
    sp_serve.add_argument("--reload", action="store_true",
                          help="Enable auto-reload (dev mode)")
    sp_serve.set_defaults(func=_cmd_serve)

    # version
    sp_version = sub.add_parser("version", help="Show version info")
    sp_version.set_defaults(func=_cmd_version)

    # agent
    sp_agent = sub.add_parser("agent", help="Agent management")
    sp_agent_sub = sp_agent.add_subparsers(dest="agent_command")

    # agent add
    sp_add = sp_agent_sub.add_parser("add", help="Register a new agent")
    sp_add.add_argument("--name", required=True, help="Agent name")
    sp_add.add_argument("--agent-id", default=None,
                        help="Agent ID (default: auto-generated)")
    sp_add.add_argument("--agent-type", default="hermes",
                        help="Agent type: hermes, claude_code, openclaw, custom (default: hermes)")
    sp_add.add_argument("--model", default=None,
                        help="Model identifier (e.g. claude-sonnet-4)")
    sp_add.add_argument("--capabilities", default=None,
                        help="Comma-separated capabilities (e.g. coding,review)")
    sp_add.add_argument("--max-concurrent-tasks", type=int, default=2,
                        help="Max concurrent tasks (default: 2)")
    sp_add.add_argument("--host", default=None,
                        help="Coordinator host (default: localhost)")
    sp_add.add_argument("--port", type=int, default=None,
                        help="Coordinator port (default: 8765)")
    sp_add.set_defaults(func=_cmd_agent_add)

    # agent list
    sp_list = sp_agent_sub.add_parser("list", help="List registered agents")
    sp_list.set_defaults(func=_cmd_agent_list)

    # daemon
    sp_daemon = sub.add_parser("daemon", help="Run the bootstrap daemon")
    sp_daemon.add_argument("--interval", type=int, default=30,
                           help="Check interval in minutes (default: 30)")
    sp_daemon.add_argument("--dry-run", action="store_true",
                           help="Only detect work, don't execute")
    sp_daemon.add_argument("--once", action="store_true",
                           help="Run once and exit (no loop)")
    sp_daemon.set_defaults(func=_cmd_daemon)

    # migrate
    from agora.cli_migrate import add_migrate_parser
    add_migrate_parser(sub)

    return parser


def main() -> None:
    """CLI entry point."""
    parser = build_parser()
    args = parser.parse_args()

    if not args.command:
        parser.print_help()
        sys.exit(1)

    # `agora agent` without subcommand
    if args.command == "agent" and not getattr(args, "agent_command", None):
        parser.parse_args(["agent", "--help"])
        sys.exit(1)

    args.func(args)


if __name__ == "__main__":
    main()
